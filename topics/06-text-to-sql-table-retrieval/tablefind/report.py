r"""Build results.md and the blog graphs from the saved run files only.

    $env:PYTHONPATH = "../..;."
    python -m tablefind.report
"""

from __future__ import annotations

import sys
from pathlib import Path
from statistics import mean

from shared.charts import bar_chart, money, pct
from shared.runs import latest_run
from tablefind.data import load_key, load_links, load_next3
from tablefind.joins import add_joins, add_search
from tablefind.score import by_gold_size, score

TOPIC = Path(__file__).resolve().parent.parent
RUNS_DIR = TOPIC / "runs"
CHARTS_DIR = TOPIC / "charts"
LEVEL_NAMES = {"0": "0 · Keyword search", "1": "1 · Embedding search",
               "2": "2 · Search 20, LLM picks 7", "3": "3 · + descriptions",
               "4c": "4c · 3 + 3 from search", "4": "4 · 3 + 3 joined tables",
               "5": "5 · Pinterest summaries", "5j": "5j · 5 + 3 joined tables"}  # short: the chart's label column is narrow
RUN_LEVELS = ("0", "1", "2", "3", "5")  # 4 and 4c are computed from level 3's saved answers, 5j from level 5's
GOLD_SIZE_LEVELS = ("1", "2", "3", "4")
GOLD_SIZE_LEGEND = {"1": "1 · Search", "2": "2 · LLM picks", "3": "3 · + descriptions", "4": "4 · + joins"}  # fits one row  # four colours at most; level 0 is near zero everywhere
SET_NAMES = {"main": "Main set (tuning allowed)", "test": "Held-out set (never tuned on)"}


def _derive(run: dict, extend, base: str = "3") -> dict:
    """A copy of a level `base` run with each ok answer's picks extended. Costs and timings stay the base level's."""
    reps = []
    for r in run["repeats"]:
        answers = {q: ({**a, "picks": extend(q, a)} if a["status"] == "ok" else dict(a)) for q, a in r["answers"].items()}
        reps.append({**r, "answers": answers})
    return {**run, "repeats": reps, "derived_from": base}


def level_runs(runs_dir: Path, set_name: str) -> dict[str, dict | None]:
    runs = {lv: latest_run(runs_dir, set_name, lv) for lv in RUN_LEVELS}
    links = load_links() if runs["3"] or runs["5"] else {}
    joined = lambda q, a: add_joins(a["picks"], a["top20"] or [], links)  # noqa: E731
    three, five = runs["3"], runs["5"]
    next3 = load_next3() if three else {}
    runs["4c"] = _derive(three, lambda q, a: add_search(a["picks"], next3[q])) if three else None
    runs["4"] = _derive(three, joined) if three else None
    runs["5j"] = _derive(five, joined, base="5") if five else None
    return {lv: runs[lv] for lv in LEVEL_NAMES}  # the reading order: 4c and 4 build on 3, then 5


def summary(run: dict, key: dict[str, set[str]]) -> dict:
    """Scores averaged over the run's repeats, plus $ and seconds per question."""
    per = [score(r["answers"], {q: key[q] for q in r["answers"]}) for r in run["repeats"]]

    def avg(field):
        vals = [getattr(s, field) for s in per]
        return None if any(v is None for v in vals) else mean(vals)

    first = run["repeats"][0]
    shortlisted = [a for r in run["repeats"] for a in r["answers"].values() if a.get("top20") is not None]
    llm = list(first.get("llm_seconds", {}).values())
    return {"n": avg("n"), "all_found": avg("all_found"), "recall": avg("recall"), "ceiling": avg("ceiling"),
            "made_up": avg("made_up"), "errors": avg("errors"), "failed": avg("failed"),
            # repeat 1 only: later repeats send the same prompts and hit the provider's prompt cache
            "usd": mean(first["cost_usd"].values()) if first["cost_usd"] else 0.0,
            "seconds": mean(first["seconds"].values()) if first["seconds"] else 0.0,
            "llm_seconds": mean(llm) if llm and any(llm) else None,
            "filled_avg": mean(a["filled"] for a in shortlisted) if shortlisted else None,
            "filled_share": mean(a["filled"] > 0 for a in shortlisted) if shortlisted else None,
            "repeats": len(run["repeats"])}


def _p(v) -> str:
    return "—" if v is None else f"{v:.0%}"


def build_results(runs_dir: Path) -> str:
    lines = ["# Results", "", "Generated by `python -m tablefind.report` from the run files in `runs/`. "
             "Smoke runs (`--limit`) and runs stopped by the budget are left out.", "",
             "**All found** = every table the question needs is in the 7 handed over. **Recall** = share of needed tables found. "
             "**Top-20 ceiling** = all needed tables were in the 20 the LLM was shown. **Made up** = answers naming a table it wasn't shown. "
             "**Filled from search** = when the LLM named fewer than 7 usable tables, the rest came from the search order: "
             "average tables filled per answer (share of answers with any fill). "
             "**$ / question** = repeat 1 only (later repeats hit the provider's prompt cache), without the one-time embedding of the 971 tables. "
             "**s / question** = wall time with parallel workers; **LLM s** = the re-ranker call alone. "
             "**Levels 4c, 4 and 5j hand over 10 tables, not 7**: level 3's picks plus 3 more, from the search order (4c, the control) "
             "or joined to the picks by a foreign key (4); 5j is level 5's picks plus 3 joined tables. They reuse level 3's "
             "or level 5's answers, so they cost nothing extra.", ""]
    for set_name, title in SET_NAMES.items():
        key = load_key(set_name)
        runs = level_runs(runs_dir, set_name)
        lines += [f"## {title}: {len(key)} questions", "",
                  "| Level | n | All found | Recall | Top-20 ceiling | Made up | Filled from search | Errors | API failures | Repeats | $ / question | s / question | LLM s |",
                  "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for lv, name in LEVEL_NAMES.items():
            run = runs[lv]
            if run is None:
                lines.append(f"| {name} | not run | | | | | | | | | | | |")
                continue
            s = summary(run, key)
            filled = "—" if s["filled_avg"] is None else f"{s['filled_avg']:.1f} ({s['filled_share']:.0%})"
            llm = "—" if s["llm_seconds"] is None else f"{s['llm_seconds']:.2f}"
            lines.append(f"| {name} | {s['n']:.0f} | {_p(s['all_found'])} | {_p(s['recall'])} | {_p(s['ceiling'])} | {_p(s['made_up'])} | "
                         f"{filled} | {s['errors']:.1f} | {s['failed']:.1f} | {s['repeats']} | ${s['usd']:.5f} | {s['seconds']:.2f} | {llm} |")
        lines.append("")
        sizes = {lv: [by_gold_size(r["answers"], key) for r in run["repeats"]] for lv, run in runs.items() if run}
        if sizes:
            lines += ["All found, by how many tables the question needs:", "", "| Level | 1 table | 2 tables | 3+ tables |", "|---|---|---|---|"]
            for lv, reps in sizes.items():
                cells = [_p(mean(r[b] for r in reps)) if all(b in r for r in reps) else "—" for b in ("1", "2", "3+")]
                lines.append(f"| {LEVEL_NAMES[lv]} | " + " | ".join(cells) + " |")
            counts = {b: sum(1 for g in key.values() if (str(len(g)) if len(g) < 3 else "3+") == b) for b in ("1", "2", "3+")}
            lines += ["", f"Questions per group: 1 table {counts['1']}, 2 tables {counts['2']}, 3+ tables {counts['3+']}.", ""]
    lines += ["## Against the article", "",
              "**Article says:** table recall goes up when an LLM re-ranks the search results, and again with descriptions "
              "(LinkedIn's Figure 6, no numbers given).", ""]
    test = level_runs(runs_dir, "test")
    if all(test[lv] for lv in ("1", "2", "3")):
        key = load_key("test")
        f = {lv: summary(test[lv], key)["all_found"] for lv in ("1", "2", "3", "4c", "4")}
        lines.append(f"**We got (held-out, all found):** embedding search {f['1']:.0%} → LLM re-rank {f['2']:.0%} → "
                     f"+ descriptions {f['3']:.0%}. With 3 more tables (10 in all): from search {f['4c']:.0%}, "
                     f"joined by foreign key {f['4']:.0%}."
                     + (f" Pinterest-style summaries: {summary(test['5'], key)['all_found']:.0%}, "
                        f"plus 3 joined tables: {summary(test['5j'], key)['all_found']:.0%}." if test["5"] else ""))
    else:
        lines.append("**We got:** not run yet.")
    return "\n".join(lines) + "\n"


def build_charts(runs_dir: Path, out_dir: Path = CHARTS_DIR) -> list[Path]:
    sets = {s: level_runs(runs_dir, s) for s in SET_NAMES}
    if not any(r for runs in sets.values() for r in runs.values()):
        return []
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    keys = {s: load_key(s) for s in SET_NAMES}
    sums = {s: {lv: summary(r, keys[s]) for lv, r in runs.items() if r} for s, runs in sets.items()}

    def save(name: str, svg: str) -> None:
        (out_dir / name).write_text(svg, encoding="utf-8")
        written.append(out_dir / name)

    panels = [(title, [LEVEL_NAMES[lv] for lv in sums[s]], [[v["all_found"], v["recall"]] for v in sums[s].values()])
              for s, title in SET_NAMES.items() if sums[s]]
    save("all-found.svg", bar_chart("Did the tables handed over include everything needed?",
                                    "Out of 971 tables; 7 handed over (10 for 4c, 4, 5j). All found = every needed table is there; recall = share found",
                                    panels, [("All found", "s1"), ("Recall", "s2")], 1.0, pct))

    panels = [(title, [LEVEL_NAMES[lv] for lv in ("2", "3", "5") if lv in sums[s]],
               [[sums[s][lv]["ceiling"], sums[s][lv]["all_found"]] for lv in ("2", "3", "5") if lv in sums[s]])
              for s, title in SET_NAMES.items()]
    panels = [p for p in panels if p[1]]
    if panels:
        save("ceiling.svg", bar_chart("What search found vs. what the LLM kept",
                                      "All needed tables in the 20 shown to the LLM, and in the 7 it picked",
                                      panels, [("In the 20 (search)", "muted"), ("In the 7 handed over", "s1")], 1.0, pct))

    test = sets["test"]
    if any(test.values()):
        cats, rows = [], []
        for b, label in (("1", "1 table"), ("2", "2 tables"), ("3+", "3+ tables")):
            row = []
            for lv in GOLD_SIZE_LEVELS:
                reps = [by_gold_size(r["answers"], keys["test"]) for r in test[lv]["repeats"]] if test[lv] else None
                row.append(mean(r[b] for r in reps) if reps and all(b in r for r in reps) else None)
            cats.append(label)
            rows.append(row)
        lv_series = [(GOLD_SIZE_LEGEND[lv], c) for lv, c in zip(GOLD_SIZE_LEVELS, ("muted", "s1", "s2", "s3"))]
        save("by-gold-size.svg", bar_chart("Held-out: harder when a question needs more tables",
                                           "All found, by how many tables the question needs",
                                           [("", cats, rows)], lv_series, 1.0, pct))

    paid = [(lv, v) for lv, v in sums["main"].items() if lv in ("2", "3", "5")]
    if paid:
        top = max(v["usd"] for _, v in paid) * 1.3
        save("cost-per-question.svg", bar_chart("Cost per question", "Main set, list prices; levels 0–1 cost almost nothing",
                                                [("", [LEVEL_NAMES[lv] for lv, _ in paid], [[v["usd"]] for _, v in paid])],
                                                [("$ per question", "s1")], top, money))
    return written


def main() -> int:
    (TOPIC / "results.md").write_text(build_results(RUNS_DIR), encoding="utf-8")
    for p in build_charts(RUNS_DIR):
        print(f"Wrote {p.relative_to(TOPIC)}")
    print("Wrote results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
